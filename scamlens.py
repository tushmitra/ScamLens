import numpy as np
import pandas as pd
from sklearn.metrics import recall_score

SAFE_THRESHOLD = 0.20
SCAM_THRESHOLD = 0.70


def get_scam_probability(trained_model, texts):
    probabilities = trained_model.predict_proba(texts)

    # Locate label 0 (legitimate) rather than assuming its column position.
    classes = list(trained_model.classes_)
    legit_index = classes.index(0)

    return 1 - probabilities[:, legit_index]


def get_verdict(probability):
    if probability < SAFE_THRESHOLD:
        return "Safe"
    elif probability < SCAM_THRESHOLD:
        return "Suspicious"
    else:
        return "Scam"


for model_name, trained_model in models.items():
    p_scam = get_scam_probability(trained_model, X_test)

    results = pd.DataFrame({
        "text": list(X_test),
        "actual_label": np.asarray(y_test),
        "p_scam": p_scam
    })

    results["verdict"] = results["p_scam"].apply(get_verdict)

    actual_scam = (results["actual_label"] != 0).astype(int)

    # Both Suspicious and Scam count as alerts.
    alerts = (results["p_scam"] >= SAFE_THRESHOLD).astype(int)

    scam_recall = recall_score(
        actual_scam, alerts, zero_division=0
    )

    legitimate_mask = actual_scam == 0
    false_alarm_rate = (
        ((alerts == 1) & legitimate_mask).sum()
        / max(legitimate_mask.sum(), 1)
    )

    print(f"\n{'=' * 55}")
    print(model_name)
    print(f"{'=' * 55}")

    print(f"Scam recall: {scam_recall:.2%}")
    print(f"False alarm rate: {false_alarm_rate:.2%}")

    print("\nVerdict distribution:")
    print(results["verdict"].value_counts())

    print("\nSample predictions:")
    display(results[
        ["text", "actual_label", "p_scam", "verdict"]
    ].head(10))

