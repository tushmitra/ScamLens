def make_word_vectorizer():
    return TfidfVectorizer(
        analyzer="word",
        ngram_range=(1, 2),
        min_df=1,
        max_features=100000,
        sublinear_tf=True
    )

def make_word_char_features():
    return FeatureUnion([
        ("word", make_word_vectorizer()),
        ("char", TfidfVectorizer(
            analyzer="char_wb",
            ngram_range=(3, 5),
            min_df=1,
            max_features=150000,
            sublinear_tf=True
        ))
    ])

